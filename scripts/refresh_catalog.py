"""Regenerate the English catalogs from ``strings.json``.

``custom_components/aivi/strings.json`` is the one place English copy is
written. Two files are derived from it:

- ``custom_components/aivi/translations/en.json``: an exact copy, the file
  Home Assistant serves for English.
- ``frontend/src/translations/en.ts``: the ``config_panel`` section
  flattened to dot keys, the panel's bundled fallback catalog and the
  source of its ``TranslationKey`` type.

After editing ``strings.json``, run:

    uv run python scripts/refresh_catalog.py

With ``--check`` it writes nothing and exits non-zero if either file is
stale (used by `make check` and CI).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
COMPONENT = ROOT / "custom_components" / "aivi"
STRINGS = COMPONENT / "strings.json"
EN_JSON = COMPONENT / "translations" / "en.json"
EN_TS = ROOT / "frontend" / "src" / "translations" / "en.ts"

HEADER = """\
// GENERATED by scripts/refresh_catalog.py from the config_panel section of
// custom_components/aivi/strings.json (run `make catalog`); do not edit by
// hand. The English catalog: the panel's complete set of user-facing
// strings, and the compile-time source of the TranslationKey union.
"""


def _flatten(node: dict[str, Any], prefix: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    for key, value in node.items():
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, str):
            out[path] = value
        else:
            out.update(_flatten(value, path))
    return out


def en_module(strings: dict[str, Any]) -> str:
    lines = [HEADER, "export const en = {"]
    group = None
    for key, value in _flatten(strings["config_panel"]).items():
        head = key.split(".", 1)[0]
        # A blank line between top-level sections keeps the file skimmable.
        if group is not None and head != group:
            lines.append("")
        group = head
        lines.append(f"  {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)},")
    lines.append("} as const;")
    return "\n".join(lines) + "\n"


def generated() -> dict[Path, str]:
    raw = STRINGS.read_text(encoding="utf-8")
    return {EN_JSON: raw, EN_TS: en_module(json.loads(raw))}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in generated().items():
        name = path.relative_to(ROOT)
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == text:
            print(f"{name} is up to date")
            continue
        if check:
            stale.append(name)
            continue
        path.write_text(text, encoding="utf-8")
        print(f"{name} regenerated")
    if stale:
        names = " and ".join(str(name) for name in stale)
        verb = "is" if len(stale) == 1 else "are"
        print(
            f"error: {names} {verb} stale; run "
            "`uv run python scripts/refresh_catalog.py` (or `make catalog`)",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
