"""Regenerate the template metadata module of the panel harness.

The dev harness mocks the ``aivi/templates`` WebSocket command with a META
literal derived from the real template registry, written to
``frontend/harness/meta.generated.js``. After changing
``custom_components/aivi/templates/`` (or the block metadata), run:

    uv run python scripts/refresh_harness_meta.py

With ``--check`` it writes nothing and exits non-zero if the module is
stale (used by `make check` and CI).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
META_MODULE = ROOT / "frontend" / "harness" / "meta.generated.js"
NAME = META_MODULE.relative_to(ROOT)

HEADER = (
    "// GENERATED by scripts/refresh_harness_meta.py from the template\n"
    "// registry (run `make meta`); do not edit by hand.\n"
)


def generated_module() -> str:
    # Imported here: the repository root has to be on sys.path first.
    sys.path.insert(0, str(ROOT))
    from custom_components.aivi.metadata import describe_registry  # noqa: PLC0415
    from custom_components.aivi.templates import (  # noqa: PLC0415
        default_activity_registry,
        default_registry,
    )

    meta = describe_registry(default_registry(), default_activity_registry())
    return f"{HEADER}export const META = {json.dumps(meta, indent=2)};\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    text = generated_module()
    current = META_MODULE.read_text(encoding="utf-8") if META_MODULE.exists() else ""
    if current == text:
        print(f"{NAME} is up to date")
        return 0
    if check:
        print(
            f"error: {NAME} is stale; run "
            "`uv run python scripts/refresh_harness_meta.py` (or `make meta`)",
            file=sys.stderr,
        )
        return 1
    META_MODULE.write_text(text, encoding="utf-8")
    print(f"{NAME} regenerated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
