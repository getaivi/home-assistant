"""Generate the panel's inline brand mark from the real brand asset.

The mark is inlined as a data URI so the panel header never depends on a
second static file (a missing one shows a broken-image icon). It is
downscaled first: ``brand/icon.png`` verbatim is ~55 kB of base64 for a
28 px mark. ``--check`` fails when the checked-in output no longer matches
what ``brand/icon.png`` would produce.

Usage: ``make brand`` (or ``--check`` in CI, via ``make check``).
"""

from __future__ import annotations

import argparse
import base64
import io
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "custom_components" / "aivi" / "brand" / "icon.png"
TARGET = ROOT / "frontend" / "src" / "brand-mark.ts"

#: Rendered at 28 px; 84 covers a 3x display.
SIZE = 84

HEADER = """// GENERATED by scripts/refresh_brand_mark.py. Do not edit.
//
// The brand mark, downscaled from custom_components/aivi/brand/icon.png
// and inlined so the panel header never depends on a second file being
// fetchable: an unregistered static path or a missing copy renders a
// broken-image icon.
//
// Regenerate with `make brand`; `make check` fails if it drifts from the
// brand asset, so brand/ stays the single source of truth.

export const BRAND_MARK =
  "{data_uri}";
"""


def render() -> str:
    with Image.open(SOURCE) as image:
        mark = image.convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
    buffer = io.BytesIO()
    # optimize + max compression: this string ships in every panel load.
    mark.save(buffer, format="PNG", optimize=True, compress_level=9)
    encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
    return HEADER.format(data_uri=f"data:image/png;base64,{encoded}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the generated file is stale instead of writing it",
    )
    args = parser.parse_args()

    generated = render()
    if args.check:
        current = TARGET.read_text(encoding="utf8") if TARGET.exists() else ""
        if current != generated:
            print(
                f"{TARGET.relative_to(ROOT)} is stale: run `make brand`",
                file=sys.stderr,
            )
            return 1
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        return 0

    TARGET.write_text(generated, encoding="utf8")
    size = len(generated.encode("utf8")) // 1024
    print(f"{TARGET.relative_to(ROOT)} regenerated (~{size} kB inline)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
